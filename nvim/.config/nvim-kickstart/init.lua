-- Sync clipboard between OS and Neovim.
--  Schedule the setting after `UiEnter` because it can increase startup-time.
--  Remove this option if you want your OS clipboard to remain independent.
--  See `:help 'clipboard'`
vim.schedule(function() vim.o.clipboard = 'unnamedplus' end)

-- Force OSC 52 as the clipboard provider so yanks/pastes write to the system
-- clipboard via the OUTER terminal (iTerm/tmux), not into whichever pty
-- happens to be a :terminal buffer right now. Fixes a class of bugs where
-- selecting text inside a :terminal pane (e.g. running Claude Code) ends up
-- injecting `\x1b]52;c;<base64>` into that terminal's stdin.
vim.g.clipboard = {
  name = 'OSC 52',
  copy = {
    ['+'] = require('vim.ui.clipboard.osc52').copy '+',
    ['*'] = require('vim.ui.clipboard.osc52').copy '*',
  },
  paste = {
    ['+'] = require('vim.ui.clipboard.osc52').paste '+',
    ['*'] = require('vim.ui.clipboard.osc52').paste '*',
  },
}

