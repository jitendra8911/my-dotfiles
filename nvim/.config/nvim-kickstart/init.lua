-- [[ LSP convenience commands ]]
-- This config uses Neovim's native `vim.lsp.enable`, which doesn't register the
-- old nvim-lspconfig `:LspStop`/`:LspStart` commands, so define them here.
vim.api.nvim_create_user_command('LspStop', function()
  local clients = vim.lsp.get_clients { bufnr = 0 }
  if vim.tbl_isempty(clients) then
    vim.notify('No LSP clients attached to this buffer', vim.log.levels.WARN)
    return
  end
  vim.lsp.stop_client(clients)
  vim.notify('Stopped LSP for this buffer', vim.log.levels.INFO)
end, { desc = 'Stop LSP client(s) attached to the current buffer' })

vim.api.nvim_create_user_command('LspStart', function()
  -- Re-trigger filetype detection so any enabled servers re-attach to this buffer
  vim.api.nvim_exec_autocmds('FileType', { buffer = 0 })
  vim.notify('Started LSP for this buffer', vim.log.levels.INFO)
end, { desc = 'Start/attach enabled LSP server(s) for the current buffer' })

-- [[ Basic Autocommands ]]
--  See `:help lua-guide-autocommands`

-- Highlight when yanking (copying) text
--  Try it with `yap` in normal mode
--  See `:help vim.hl.on_yank()`
vim.api.nvim_create_autocmd('TextYankPost', {
  desc = 'Highlight when yanking (copying) text',
  group = vim.api.nvim_create_augroup('kickstart-highlight-yank', { clear = true }),
  callback = function() vim.hl.on_yank() end,
})

-- Disable mouse inside :terminal buffers so iTerm owns mouse selection
-- directly. Without this, nvim's terminal mode intercepts the click-drag,
-- tries to copy via OSC 52, and the escape sequence leaks into the pty of
-- whatever app is running inside (Claude Code, etc.).
vim.api.nvim_create_autocmd('TermOpen', {
  desc = 'Disable mouse in :terminal buffers (let iTerm handle selection)',
  group = vim.api.nvim_create_augroup('user-term-mouse-off', { clear = true }),
  callback = function() vim.opt_local.mouse = '' end,
})

-- [[ Install `lazy.nvim` plugin manager ]]
--    See `:help lazy.nvim.txt` or https://github.com/folke/lazy.nvim for more info
local lazypath = vim.fn.stdpath 'data' .. '/lazy/lazy.nvim'
if not (vim.uv or vim.loop).fs_stat(lazypath) then
  local lazyrepo = 'https://github.com/folke/lazy.nvim.git'
  local out = vim.fn.system { 'git', 'clone', '--filter=blob:none', '--branch=stable', lazyrepo, lazypath }
  if vim.v.shell_error ~= 0 then error('Error cloning lazy.nvim:\n' .. out) end
end

---@type vim.Option
local rtp = vim.opt.rtp
rtp:prepend(lazypath)

